"""Builds shared/levels.js from the act files in tools/acts/.

    python3 tools/levelgen.py              write shared/levels.js
    python3 tools/levelgen.py --show 5,6   also print those maps with rulers

The DSL lives in tools/lvdsl.py. Levels live in tools/acts/act*.py, each
registered with @level(n).

Three people edit the act files at the same time, so one broken file must not
break the others. If an act file fails to import, or a level function raises,
that level keeps its last good build (tools/acts/.last/level-N.json) and the
error is printed. A level that has never built is a flat stub marked stub: true.
"""
import importlib, json, os, sys, tempfile, traceback

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, 'acts'))
import lvdsl  # noqa: E402

N_LEVELS = 32
ACTS = sorted(f[:-3] for f in os.listdir(os.path.join(HERE, 'acts')) if f.startswith('act') and f.endswith('.py'))
LAST = os.path.join(HERE, 'acts', '.last')
OUT = os.path.join(HERE, '..', 'shared', 'levels.js')


def stub(n):
    L = lvdsl.Lv(f'Level {n} (not built)', 30, 'This level has not been built yet.')
    L.floor()
    L.p(3, 27, 'a').p(5, 27, 'b').p(34, 27, 'A').p(36, 27, 'B')
    d = L.data()
    d['stub'] = True
    return d


def validate(n, d):
    flat = ''.join(d['map'])
    for ch in 'abAB':
        assert flat.count(ch) == 1, f'level {n}: needs exactly one "{ch}", found {flat.count(ch)}'
    assert len(d['map']) == 30 and all(len(r) == 40 for r in d['map']), f'level {n}: map must be 40x30'


def atomic_write(path, text):
    fd, tmp = tempfile.mkstemp(dir=os.path.dirname(path))
    with os.fdopen(fd, 'w') as f:
        f.write(text)
    os.replace(tmp, path)


def show(n, d):
    print(f'\n--- level {n}: {d["name"]}   (x across, y down; same coordinates as the DSL)')
    print('    ' + ''.join(str(x // 10) if x % 10 == 0 else ' ' for x in range(40)))
    print('    ' + ''.join(str(x % 10) for x in range(40)))
    for y, row in enumerate(d['map']):
        print(f'{y:3d} {row}')
    for k in ('moves', 'inv', 'leverOn', 'plats'):
        if k in d: print(f'    {k}: {json.dumps(d[k])}')


def main():
    errors = []
    for act in ACTS:
        try:
            importlib.import_module(act)
        except Exception:
            errors.append(f'{act}.py failed to import:\n{traceback.format_exc()}')
    os.makedirs(LAST, exist_ok=True)
    datas, built, kept, stubs = [], 0, [], []
    for n in range(1, N_LEVELS + 1):
        last = os.path.join(LAST, f'level-{n}.json')
        d = None
        if n in lvdsl.REGISTRY:
            try:
                d = lvdsl.REGISTRY[n]().data()
                validate(n, d)
                atomic_write(last, json.dumps(d))
                built += 1
            except Exception:
                errors.append(f'level {n} failed to build:\n{traceback.format_exc()}')
                d = None
        if d is None and os.path.exists(last):
            d = json.load(open(last)); kept.append(n)
        if d is None:
            d = stub(n); stubs.append(n)
        datas.append(d)

    lines = ['// Generated by tools/levelgen.py from tools/acts/*.py. Do not edit by hand.',
             '// Legend: see the top of tools/lvdsl.py.', 'export const LEVELS = [']
    for d in datas:
        lines.append('  {')
        lines.append(f'    name: {json.dumps(d["name"])}, par: {d["par"]},')
        if 'hint' in d: lines.append(f'    hint: {json.dumps(d["hint"])},')
        if d.get('stub'): lines.append('    stub: true,')
        for k in ('moves', 'inv', 'leverOn', 'plats'):
            if k in d: lines.append(f'    {k}: {json.dumps(d[k])},')
        lines.append('    map: [')
        for row in d['map']:
            lines.append('      ' + json.dumps(row) + ',')
        lines.append('    ],')
        lines.append('  },')
    lines.append('];')
    atomic_write(OUT, '\n'.join(lines) + '\n')
    print(f'wrote {len(datas)} levels to shared/levels.js: {built} built'
          + (f', kept last good build for {kept}' if kept else '')
          + (f', {len(stubs)} stubs' if stubs else ''))
    if '--show' in sys.argv:
        i = sys.argv.index('--show')
        for n in [int(v) for v in sys.argv[i + 1].split(',')]:
            show(n, datas[n - 1])
    for e in errors:
        print('\nERROR: ' + e, file=sys.stderr)
    sys.exit(1 if errors else 0)


if __name__ == '__main__':
    main()
